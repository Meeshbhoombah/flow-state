import { createHash } from "node:crypto";
import express from "express";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StreamableHTTPServerTransport } from "@modelcontextprotocol/sdk/server/streamableHttp.js";
import { z } from "zod";
import {
  enforceSignedToolPolicy,
  TOOL_ACTION,
  TOOL_ID,
} from "./tool_policy.js";

const HOST = "127.0.0.1";
const PORT = 3000;
const ENDPOINT = "/mcp";

const app = express();
app.use(express.json());

function analyzeDemo(filename: string, sourceCode: string) {
  const sourceHash = createHash("sha256")
    .update(sourceCode)
    .digest("hex");

  // Deliberately deterministic demo output.
  // This is NOT a general-purpose Solidity analyzer.
  const hasExternalCall = sourceCode.includes(".call");
  const resetsBalanceAfterCall =
    /\.call[\s\S]*?balances\s*\[\s*msg\.sender\s*\]\s*=\s*0\s*;/
      .test(sourceCode);

  const findings = hasExternalCall && resetsBalanceAfterCall
    ? [
        {
          id: "DEMO-001",
          severity: "high" as const,
          title: "Potential reentrancy: state updated after external call",
          file: filename,
          line: 1,
          evidence:
            "Demo heuristic detected an external .call and a subsequent " +
            "balances[msg.sender] = 0 assignment. Verify the actual source " +
            "and control flow before treating this as a confirmed finding.",
        },
      ]
    : [];

  return {
    status: "demo",
    filename,
    source_sha256: sourceHash,
    summary:
      "Deterministic demo response. This result is generated by a simple " +
      "string heuristic, not a complete security assessment.",
    findings,
  };
}

function createSecurityServer() {
  const server = new McpServer({
    name: TOOL_ID,
    version: "1.0.0",
  });

  server.tool(
    TOOL_ACTION,
    "Return a deterministic demo security assessment for Solidity source. " +
      "This tool is for testing signed tool policies and response contracts, " +
      "not for production audits.",
    {
      filename: z.string().min(1),
      source_code: z.string().min(1),
    },
    async ({ filename, source_code }) => {
      // Fail closed before any analysis or tool side effect.
      await enforceSignedToolPolicy(TOOL_ID, TOOL_ACTION);

      console.log("Signed tool policy verified:", {
        toolId: TOOL_ID,
        action: TOOL_ACTION,
        filename,
      });

      const result = analyzeDemo(filename, source_code);

      return {
        content: [
          {
            type: "text" as const,
            text: JSON.stringify(result),
          },
        ],
        structuredContent: result,
      };
    },
  );

  return server;
}

app.use(ENDPOINT, (req, _res, next) => {
  console.log("Incoming MCP request:", {
    method: req.method,
    contentType: req.headers["content-type"],
  });
  next();
});

// Stateless HTTP transport: each request gets a fresh MCP server/transport.
app.post(ENDPOINT, async (req, res) => {
  const server = createSecurityServer();
  const transport = new StreamableHTTPServerTransport({
    sessionIdGenerator: undefined,
    enableJsonResponse: true,
  });

  res.on("close", () => {
    void transport.close();
    void server.close();
  });

  try {
    await server.connect(transport);

    // ArmorIQ adds _iam_context to the top-level request body.
    // Remove it from the JSON-RPC message passed to MCP.
    const incoming = req.body as Record<string, unknown>;
    const iamContext = incoming?._iam_context;

    const jsonRpcBody = { ...incoming };
    delete jsonRpcBody._iam_context;

    console.log("ArmorIQ context present:", iamContext !== undefined);

    await transport.handleRequest(req, res, jsonRpcBody);
  } catch (error: unknown) {
    console.error("MCP request failed:", error);

    if (!res.headersSent) {
      res.status(500).json({
        error: "Internal MCP server error",
      });
    }
  }
});

app.get(ENDPOINT, (_req, res) => {
  res.status(405).json({
    error: "GET is not supported by this stateless demo server",
  });
});

app.delete(ENDPOINT, (_req, res) => {
  res.status(405).json({
    error: "Sessions are not supported by this stateless demo server",
  });
});

app.listen(PORT, HOST, () => {
  console.log(
    `Security assessment MCP listening on http://${HOST}:${PORT}${ENDPOINT}`,
  );
  console.log(`Tool: ${TOOL_ID}.${TOOL_ACTION}`);
  console.log("Mode: signed-policy enforcement enabled");
});

